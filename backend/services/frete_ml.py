NOME_TABELA = {"verde": "MercadoLíder, verde ou sem reputação", "amarela": "reputação amarela",
               "laranja": "reputação laranja ou vermelha"}
_TABELA_DO_TERMOMETRO = {"5_green": "verde", "4_light_green": "verde", "3_yellow": "amarela",
                         "2_orange": "laranja", "1_red": "laranja"}


def tabela_da_reputacao(level_id: str | None) -> str:
    return _TABELA_DO_TERMOMETRO.get(level_id or "", "verde")


def peso_cobrado_kg(dimensoes: str) -> float | None:
    """dimensoes = "AxLxC,gramas" (formato do ML). Maior entre o peso real e o volumétrico."""
    try:
        medidas, gramas = dimensoes.split(",")
        a, l, c = (float(x) for x in medidas.lower().split("x"))
        return max(float(gramas) / 1000, a * l * c / 6000)
    except (ValueError, AttributeError):
        return None


def custo(preco: float, dimensoes: str, tabela: str = "verde") -> tuple[float, float] | None:
    """(custo do envio para o vendedor, peso cobrado em kg)."""
    peso = peso_cobrado_kg(dimensoes)
    if peso is None or preco <= 0:
        return None
    linha = TABELAS.get(tabela, TABELAS["verde"])[min(bisect_left(LIMITES_PESO_KG, peso), len(LIMITES_PESO_KG))]
    valor = linha[sum(preco >= inicio for inicio in INICIO_FAIXA_PRECO) - 1]
    if preco < 19:
        valor = min(valor, preco / 2)
    return round(valor, 2), round(peso, 3)
